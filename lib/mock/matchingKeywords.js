// 영문 낱말은 다른 단어 안에 들어 있을 때(build 속 ui) 맞지 않도록 앞뒤가 영문이 아닐 때만 찾는다.
function includesKeyword(text, keyword) {
  if (!/^[a-z.]+$/.test(keyword)) return text.includes(keyword);
  return new RegExp(`(^|[^a-z])${keyword.replace(".", "\\.")}([^a-z]|$)`).test(text);
}

export function mentionsCompetency(text, name) {
  const lower = text.toLowerCase();
  return (KEYWORDS[name] ?? [name]).some((keyword) => includesKeyword(lower, keyword.toLowerCase()));
}
